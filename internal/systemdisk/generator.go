package systemdisk

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// failureUnit fails local-fs.target when the system disk cannot be resolved,
// so the node stops in emergency mode before anything writes to /var.
const failureUnit = "katl-system-disk.service"

const failureMessageFile = "katl-system-disk.error"

// Device is a block device number.
type Device struct {
	Major, Minor uint32
}

// Boot describes the system the generator runs on.
type Boot struct {
	Sysfs   string
	Cmdline string
	Initrd  bool
	Root    Device
	// Var and EFI are set when that path is already mounted from a device
	// other than the root's, as when daemon-reload reruns the generator.
	Var *Device
	EFI *Device
}

// Generate writes the generator output for boot into dir.
func Generate(dir string, boot Boot) error {
	// The initrd mounts only the root; /efi and /var belong to the booted
	// system. A runtime image booted directly, as in development VMs, does not
	// select its root by PARTUUID and has no system disk.
	if boot.Initrd || !strings.Contains(" "+boot.Cmdline, " root=PARTUUID=") {
		return nil
	}
	if boot.Var != nil {
		return regenerate(dir, boot)
	}
	layout, err := Resolve(boot.Sysfs, boot.Root.Major, boot.Root.Minor, true)
	if err != nil {
		return errors.Join(err, WriteFailure(dir, err))
	}
	if err := writeMounts(dir, layout.ESP.DevicePath(), layout.State.DevicePath()); err != nil {
		return errors.Join(err, WriteFailure(dir, err))
	}
	return nil
}

// regenerate keeps describing the mounts this boot already made. The boot
// checks passed when they were made, and a disk attached since must not
// replace or fail units that are in use.
func regenerate(dir string, boot Boot) error {
	state, err := partitionOf(boot.Sysfs, *boot.Var)
	if err != nil {
		return fmt.Errorf("describe mounted /var: %w", err)
	}
	esp := ""
	switch {
	case boot.EFI != nil:
		partition, err := partitionOf(boot.Sysfs, *boot.EFI)
		if err != nil {
			return fmt.Errorf("describe mounted /efi: %w", err)
		}
		esp = partition.DevicePath()
	default:
		if layout, err := Resolve(boot.Sysfs, boot.Root.Major, boot.Root.Minor, false); err == nil {
			esp = layout.ESP.DevicePath()
		}
	}
	return writeMounts(dir, esp, state.DevicePath())
}

// writeMounts writes the system disk mounts. /var is required: a state
// partition that never appears or fails to mount stops the boot. /efi is
// wanted, because the running system does not need it until it changes boot
// entries, and those operations report an unmounted ESP. An empty esp omits
// efi.mount.
func writeMounts(dir, esp, state string) error {
	if err := writeUnit(dir, "var.mount", mountUnit("Katl writable state partition", state, "/var", "auto", "rw"), "local-fs.target.requires"); err != nil {
		return err
	}
	if esp == "" {
		return nil
	}
	return writeUnit(dir, "efi.mount", mountUnit("Katl EFI system partition", esp, "/efi", "vfat", "rw,umask=0077"), "local-fs.target.wants")
}

// WriteFailure writes generator output that stops the boot with the reason
// and recovery guidance instead of mounting partitions from an uncertain disk.
func WriteFailure(dir string, cause error) error {
	guidance := "Check the disks attached to the node, then reboot."
	var failure *Failure
	if errors.As(cause, &failure) {
		guidance = failure.Guidance
	}
	message := fmt.Sprintf("KatlOS could not identify its system disk: %v.\nKatlOS mounts /efi and /var only from the disk that holds the running root partition, and did not mount them.\n%s\nIf this boot was an upgrade trial, powering the node off and on returns to the previous generation.\n", cause, guidance)
	if err := os.WriteFile(filepath.Join(dir, failureMessageFile), []byte(message), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", failureMessageFile, err)
	}
	unit := strings.Join([]string{
		"# Generated by katl-system-disk-generator",
		"[Unit]",
		"Description=Katl system disk identification",
		"DefaultDependencies=no",
		"Before=local-fs.target",
		"",
		"[Service]",
		"Type=oneshot",
		"StandardOutput=journal+console",
		"ExecStart=/usr/bin/cat " + filepath.Join(dir, failureMessageFile),
		"ExecStart=/usr/bin/false",
		"",
	}, "\n")
	return writeUnit(dir, failureUnit, unit, "local-fs.target.requires")
}

func mountUnit(description, what, where, filesystem, options string) string {
	return strings.Join([]string{
		"# Generated by katl-system-disk-generator",
		"[Unit]",
		"Description=" + description,
		"Documentation=man:systemd.mount(5)",
		"DefaultDependencies=no",
		"Before=local-fs.target",
		"Conflicts=umount.target",
		"Before=umount.target",
		"",
		"[Mount]",
		"What=" + what,
		"Where=" + where,
		"Type=" + filesystem,
		"Options=" + options,
		"",
	}, "\n")
}

func writeUnit(dir, name, content, dependencyDir string) error {
	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", name, err)
	}
	if err := os.MkdirAll(filepath.Join(dir, dependencyDir), 0o755); err != nil {
		return fmt.Errorf("create %s: %w", dependencyDir, err)
	}
	if err := os.Symlink("../"+name, filepath.Join(dir, dependencyDir, name)); err != nil && !os.IsExist(err) {
		return fmt.Errorf("link %s: %w", name, err)
	}
	return nil
}
